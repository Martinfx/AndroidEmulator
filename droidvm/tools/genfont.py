#!/usr/bin/env python3
"""Rasterizes printable ASCII + Latin-2 (Czech) glyphs into a C++ alpha atlas.

usage: genfont.py <font.ttf> <out.h>
The emulator scales this single-size atlas with bilinear sampling.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZE = 48  # px em size of the atlas
CHARS = [chr(c) for c in range(32, 127)] + list("áčďéěíňóřšťúůýžÁČĎÉĚÍŇÓŘŠŤÚŮÝŽäöüß°€")

font = ImageFont.truetype(sys.argv[1], SIZE)
ascent, descent = font.getmetrics()
line_h = ascent + descent

glyphs = []
for ch in CHARS:
    adv = font.getlength(ch)
    l, t, r, b = font.getbbox(ch)
    w, h = max(r - l, 0), max(b - t, 0)
    img = Image.new("L", (max(w, 1), max(h, 1)), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
    glyphs.append((ord(ch), adv, l, t, w, h, img.tobytes() if w and h else b""))

with open(sys.argv[2], "w") as out:
    out.write("// Generated by tools/genfont.py from %s - do not edit.\n" % sys.argv[1].split("/")[-1])
    out.write("#pragma once\n#include <cstdint>\n\nnamespace font_data {\n")
    out.write("constexpr int kSize = %d, kAscent = %d, kLineHeight = %d;\n" % (SIZE, ascent, line_h))
    out.write("struct Glyph { uint32_t cp; float advance; int16_t x, y, w, h; uint32_t offset; };\n")
    data = bytearray()
    out.write("constexpr Glyph kGlyphs[] = {\n")
    for cp, adv, l, t, w, h, px in sorted(glyphs):
        out.write("  {%d, %.2ff, %d, %d, %d, %d, %d},\n" % (cp, adv, l, t, w, h, len(data)))
        data += px
    out.write("};\nconstexpr uint8_t kPixels[] = {\n")
    for i in range(0, len(data), 32):
        out.write("  " + ",".join(str(x) for x in data[i:i + 32]) + ",\n")
    out.write("};\n}  // namespace font_data\n")
